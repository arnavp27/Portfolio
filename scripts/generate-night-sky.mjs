import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { DataUtils, HalfFloatType } from 'three';
import { HDRLoader } from 'three/addons/loaders/HDRLoader.js';
import {
  NIGHT_SKY_HEADER_BYTES,
  NIGHT_SKY_HEIGHT,
  NIGHT_SKY_WIDTH,
} from '../src/lib/garage/night-sky.ts';

const sourceUrl = new URL(
  '../assets-source/garage/kloofendal_overcast_puresky_1k.hdr',
  import.meta.url,
);
// Keep gzip as application data: Vite treats a .gz suffix as HTTP Content-Encoding.
const outputUrl = new URL(
  '../public/assets/garage/surfaces/night-sky.rgba16f.bin',
  import.meta.url,
);
const manifestUrl = new URL('../docs/material-sources.json', import.meta.url);
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/** Preserve the original half-float quantization before applying the authored grade. */
export function encodeNightSky(source) {
  const arrayBuffer = source.buffer.slice(source.byteOffset, source.byteOffset + source.byteLength);
  const parsed = new HDRLoader().setDataType(HalfFloatType).parse(arrayBuffer);
  if (parsed.width !== NIGHT_SKY_WIDTH || parsed.height !== NIGHT_SKY_HEIGHT)
    throw new Error('Night sky source dimensions changed.');
  const pixels = parsed.data;
  for (let i = 0; i < pixels.length; i += 4) {
    const r = DataUtils.fromHalfFloat(pixels[i]);
    const g = DataUtils.fromHalfFloat(pixels[i + 1]);
    const b = DataUtils.fromHalfFloat(pixels[i + 2]);
    const luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b;
    const cloud = luminance / (1 + luminance);
    const night = [0.002 + cloud * 0.009, 0.004 + cloud * 0.016, 0.012 + cloud * 0.037];
    for (let channel = 0; channel < 3; channel++)
      pixels[i + channel] = DataUtils.toHalfFloat(night[channel]);
  }
  const raw = Buffer.alloc(NIGHT_SKY_HEADER_BYTES + pixels.length * 2);
  raw.write('NSKY', 0, 'ascii');
  raw.writeUInt16LE(1, 4); // format version
  raw.writeUInt16LE(1, 6); // RGBA16F, little-endian
  raw.writeUInt32LE(parsed.width, 8);
  raw.writeUInt32LE(parsed.height, 12);
  for (let i = 0; i < pixels.length; i++)
    raw.writeUInt16LE(pixels[i], NIGHT_SKY_HEADER_BYTES + i * 2);
  return { raw, compressed: gzipSync(raw, { level: 9 }) };
}

export async function generateNightSky() {
  const source = await readFile(sourceUrl);
  const { raw, compressed } = encodeNightSky(source);
  await mkdir(new URL('./', outputUrl), { recursive: true });
  await writeFile(outputUrl, compressed);
  const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
  const entry = manifest.find((item) => item.asset === 'kloofendal_overcast_puresky');
  if (!entry) throw new Error('Night sky provenance entry is missing.');
  Object.assign(entry, {
    file: 'night-sky.rgba16f.bin',
    sourceFile: 'assets-source/garage/kloofendal_overcast_puresky_1k.hdr',
    sourceSha256: sha256(source),
    localSha256: sha256(compressed),
    decodedSha256: sha256(raw),
    generator: 'node scripts/generate-night-sky.mjs',
  });
  await writeFile(manifestUrl, JSON.stringify(manifest, null, 2) + '\n');
  console.log(
    `Night sky: ${source.length} source bytes → ${compressed.length} generated bytes; ${raw.length} decoded bytes.`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await generateNightSky();
